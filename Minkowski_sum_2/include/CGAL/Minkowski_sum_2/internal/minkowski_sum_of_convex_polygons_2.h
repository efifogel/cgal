/*! provides constant-time access to the vertices of a polygon by their
 * indices.
 *
 * The convolution paths (see `generate_convex_path()` and
 * `generate_single_path()`) are generated by walking along the vertices of two
 * polygons simultaneously, and they refer to the vertices by their indices: a
 * vertex of a path is the sum of the k1-th vertex of the first polygon and the
 * k2-th vertex of the second, and its identifier is computed from k1 and k2.
 * A path that is not convex may start at any pair of vertices, and it may
 * jump back and forth along each polygon; thus, its vertices cannot be
 * obtained by advancing iterators or circulators.  However,
 * `Polygon_2::operator[](i)` is `*std::next(vertices_begin(), i)`, which takes
 * time linear in `i` if the container of the polygon is not random access
 * (e.g., `std::list`): every vertex of a path then takes linear time, and
 * generating the paths takes quadratic time (with `std::list`, 308 ms instead
 * of 62 ms for polygons of 4000 vertices, measured on 2026-10-27).
 *
 * If the container of the polygon is random access (e.g., `std::vector`, the
 * default), the polygon is accessed directly, and nothing is copied.
 * Otherwise, the points of its vertices are copied once into a vector, which
 * takes linear time.  An instance must be constructed once per polygon and
 * shared by all the paths of the polygon, so that the copy is not repeated.
 * The polygon must outlive the instance and must not change.
 */
template <typename Kernel_, typename Container_>
class Random_access_vertices {
public:
  using Kernel = Kernel_;
  using Container = Container_;
  using Polygon_2 = CGAL::Polygon_2<Kernel, Container>;
  using Point_2 = typename Kernel_::Point_2;

  //! indicates whether the container of the polygon is random access.
  static constexpr bool is_random_access =
    std::is_base_of_v<std::random_access_iterator_tag,
                      typename std::iterator_traits<typename Container::const_iterator>::iterator_category>;

  explicit Random_access_vertices(const Polygon_2& pgn) : m_pgn(pgn)
  { if constexpr (! is_random_access) m_points.assign(pgn.vertices_begin(), pgn.vertices_end()); }

  //! obtains the point of the i-th vertex, in constant time.
  const Point_2& operator[](std::size_t i) const {
    if constexpr (is_random_access) return m_pgn[i];
    else return m_points[i];
  }

  //! obtains the number of vertices.
  std::size_t size() const { return m_pgn.size(); }

private:
  const Polygon_2& m_pgn;
  std::vector<Point_2> m_points;        // the copy, if not random access
};

/*! extracts the directions of the edges of a polygon.
 */
template <typename Kernel_, typename Container_, typename Traits_>
std::vector<typename Traits_::Direction_2> extract_directions(const Polygon_2<Kernel_, Container_>& pgn,
                                                              const Traits_& traits) {
  using Direction_2 = typename Traits_::Direction_2;

  const auto construct_vector = traits.construct_vector_2_object();
  const auto construct_direction = traits.construct_direction_2_object();

  std::vector<Direction_2> dirs;
  if (pgn.is_empty()) return dirs;
  auto curr = pgn.vertices_circulator();
  auto next = curr;
  do {
    ++next;
    dirs.push_back(construct_direction(construct_vector(*curr, *next)));
    curr = next;
  } while (curr != pgn.vertices_circulator());
  return dirs;
}

/*! generates the convolution path of two convex polygons, both oriented
 * counterclockwise, which is the single cycle of their edges merged in the
 * counterclockwise order of their directions.  Two edges of different
 * polygons with equal directions are traversed together.  The polygons may
 * have collinear vertices.
 *
 * The order of the directions starts right after a reference direction
 * \f$s\f$: the path starts at the first vertex of the first polygon at which
 * it turns, and \f$s\f$ is the direction of the edge that enters this vertex,
 * so that the outgoing edge is the first of the polygon in the order; a
 * direction equal to \f$s\f$ is the last in the order.  The path starts at
 * the vertex of the second polygon whose cone of directions (from the
 * direction of its incoming edge, inclusive, to the direction of its outgoing
 * edge, exclusive) contains \f$s\f$, that is, the vertex whose outgoing
 * direction precedes its incoming direction in the order.
 *
 * The order is determined by `Counterclockwise_in_between_2` alone: a
 * direction \f$a\f$ precedes a direction \f$b\f$ if and only if \f$a\f$ is
 * counterclockwise in between \f$s\f$ and \f$b\f$, as this function returns
 * `true` when its second and third arguments are equal (unless the first one
 * is equal to them, too); \f$a\f$ and \f$b\f$ are equal if neither precedes
 * the other.
 * \param pts1, pts2 the vertices of the polygons, accessed by their indices
 *        in constant time (see `Random_access_vertices`).
 * \param ids if not null, the identifiers of the vertices of the path are
 *        appended to it (see `generate_single_path()`).
 */
template <typename Kernel_, typename Container_, typename Traits_>
std::vector<typename Kernel_::Point_2>
generate_convex_path(const Random_access_vertices<Kernel_, Container_>& pts1,
                     const Random_access_vertices<Kernel_, Container_>& pts2,
                     const std::vector<typename Traits_::Direction_2>& dirs1,
                     const std::vector<typename Traits_::Direction_2>& dirs2,
                     const Traits_& traits, std::vector<std::size_t>* ids = nullptr, std::size_t id_offset = 0) {
  using Point_2 = typename Kernel_::Point_2;

  const auto construct_vector = traits.construct_vector_2_object();
  const auto construct_translated_point_2 = traits.construct_translated_point_2_object();
  const auto ccw_in_between = traits.counterclockwise_in_between_2_object();
  const auto equal = traits.equal_2_object();

  const std::size_t n1 = dirs1.size();
  const std::size_t n2 = dirs2.size();

  // The first vertex of the first polygon at which it turns.
  std::size_t k1 = 0;
  while (equal(dirs1[(k1 + n1 - 1) % n1], dirs1[k1])) {
    ++k1;
    CGAL_assertion(k1 < n1);
  }
  const auto& ref_dir = dirs1[(k1 + n1 - 1) % n1];

  // The vertex of the second polygon whose cone contains the reference
  // direction, that is, whose outgoing direction precedes its incoming
  // direction (a vertex at which the polygon does not turn has equal
  // directions).
  std::size_t k2 = 0;
  while (! ccw_in_between(dirs2[k2], ref_dir, dirs2[(k2 + n2 - 1) % n2])) {
    ++k2;
    CGAL_assertion(k2 < n2);
  }

  std::vector<Point_2> conv_path;
  conv_path.reserve(n1 + n2 + 1);
  auto add_vertex = [&]() {
    conv_path.push_back(construct_translated_point_2(pts1[k1], construct_vector(ORIGIN, pts2[k2])));
    if (ids) ids->push_back(id_offset + k1 * n2 + k2);
  };

  add_vertex();
  const std::size_t first_id = ids ? ids->back() : 0;
  std::size_t m1 = 0, m2 = 0;
  while ((m1 < n1) || (m2 < n2)) {
    const Comparison_result res = (m1 == n1) ? LARGER : (m2 == n2) ? SMALLER :
      ccw_in_between(dirs1[k1], ref_dir, dirs2[k2]) ? SMALLER :
      ccw_in_between(dirs2[k2], ref_dir, dirs1[k1]) ? LARGER : EQUAL;
    if (res != LARGER) { k1 = (k1 + 1) % n1; ++m1; }
    if (res != SMALLER) { k2 = (k2 + 1) % n2; ++m2; }
    if ((m1 == n1) && (m2 == n2)) break;
    add_vertex();
  }
  // The path is closed by the first vertex.
  conv_path.push_back(conv_path.front());
  if (ids) ids->push_back(first_id);
  return conv_path;
}

/*! computes the Minkowski sum of two convex polygons, both oriented
 * counterclockwise, directly: its boundary is the convolution cycle of the
 * two polygons, whose edges are merged in the order of their directions (see
 * `generate_convex_path()`).
 * \param traits a model of `MinkowskiSumDirectionTraits_2`
 */
template <typename Kernel_, typename Container_, typename Traits_>
Polygon_with_holes_2<Kernel_, Container_>
minkowski_sum_of_convex_polygons_2(const Polygon_2<Kernel_, Container_>& pgn1,
                                   const Polygon_2<Kernel_, Container_>& pgn2, const Traits_& traits) {
  auto path = generate_convex_path(Random_access_vertices<Kernel_, Container_>(pgn1),
                                   Random_access_vertices<Kernel_, Container_>(pgn2),
                                   extract_directions(pgn1, traits), extract_directions(pgn2, traits),
                                   traits);
  path.pop_back();
  return Polygon_with_holes_2<Kernel_, Container_>(Polygon_2<Kernel_, Container_>(path.begin(), path.end()));
}

